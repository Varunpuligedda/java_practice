class logic
{
    public static void main(String arg[]) // logical operater used to compare the two boolean functions
    {
        int a = 10;
        boolean id = true;

        System.out.println(a >= 18 && id);
        System.out.println(a >= 18 || a > 20);
        //javac logic.javaSystem.out.println(a >= 18 ! id);
    }
}